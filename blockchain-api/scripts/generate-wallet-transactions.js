'use strict';

require('dotenv').config();

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const db = require('../src/config/database');

const TX_COUNT = Number(process.env.TX_COUNT || process.argv[2] || 100);
const MIN_AMOUNT = Number(process.env.MIN_AMOUNT || 1);
const MAX_AMOUNT = Number(process.env.MAX_AMOUNT || 50);
const DEFAULT_CURRENCY = process.env.DEFAULT_CURRENCY || 'USD';
const FEE_RATE = Number(process.env.FEE_RATE || 0.001); // 1 per 1000

function getPool() {
  if (db.pool) return db.pool;
  if (typeof db.getPool === 'function') return db.getPool();
  if (typeof db.connect === 'function' && typeof db.query === 'function') return db;

  throw new Error('PostgreSQL pool not found in src/config/database.js');
}

async function getColumns(client, tableName) {
  const result = await client.query(
    `
    SELECT column_name
    FROM information_schema.columns
    WHERE table_schema = 'blockchain'
      AND table_name = $1
      AND COALESCE(is_generated, 'NEVER') = 'NEVER'
    ORDER BY ordinal_position
    `,
    [tableName]
  );

  return result.rows.map((row) => row.column_name);
}

function hasColumn(columns, column) {
  return columns.includes(column);
}

function randomAmount() {
  const amount = Math.random() * (MAX_AMOUNT - MIN_AMOUNT) + MIN_AMOUNT;
  return Number(amount.toFixed(2));
}

function calculateTransactionFee(amount) {
  return Number((Number(amount || 0) * FEE_RATE).toFixed(8));
}

function randomItem(items) {
  return items[Math.floor(Math.random() * items.length)];
}

function generateTransactionReference() {
  return `TX_${Date.now()}_${crypto.randomBytes(6).toString('hex').toUpperCase()}`;
}

function csvEscape(value) {
  const text = String(value ?? '');
  return `"${text.replace(/"/g, '""')}"`;
}

async function insertDynamicTransaction(client, transactionColumns, tx) {
  const valuesByColumn = {
    transaction_id: tx.transactionId,
    transaction_reference: tx.transactionReference,
    reference_number: tx.transactionReference,
    external_reference: tx.transactionReference,

    transaction_hash: tx.transactionHash,
    ledger_transaction_id: tx.ledgerTransactionId,
    fabric_transaction_id: tx.ledgerTransactionId,

    transaction_type: 'WALLET_TO_WALLET',
    type: 'WALLET_TO_WALLET',

    sender_wallet_id: tx.senderWalletId,
    receiver_wallet_id: tx.receiverWalletId,

    from_wallet_id: tx.senderWalletId,
    to_wallet_id: tx.receiverWalletId,

    sender_wallet_address: tx.senderWalletAddress,
    receiver_wallet_address: tx.receiverWalletAddress,

    from_wallet_address: tx.senderWalletAddress,
    to_wallet_address: tx.receiverWalletAddress,

    source_wallet_address: tx.senderWalletAddress,
    destination_wallet_address: tx.receiverWalletAddress,

    sender_customer_id: tx.senderCustomerId,
    receiver_customer_id: tx.receiverCustomerId,

    from_customer_id: tx.senderCustomerId,
    to_customer_id: tx.receiverCustomerId,

    organization_id: null,

    amount: tx.amount,
    transaction_amount: tx.amount,

    fee_amount: tx.transactionFee,
    transaction_fee: tx.transactionFee,
    fees_amount: tx.transactionFee,
    fee: tx.transactionFee,

    debit_amount: tx.totalDebitAmount,
    net_amount: tx.amount,

    currency_code: tx.currencyCode,
    currency: tx.currencyCode,

    status: 'CONFIRMED',
    transaction_status: 'CONFIRMED',

    purpose: 'Generated wallet-to-wallet test transaction',
    transaction_purpose: 'Generated wallet-to-wallet test transaction',

    description: 'Generated by scripts/generate-wallet-transactions.js',
    transaction_description: 'Generated by scripts/generate-wallet-transactions.js',

    request_source: 'NODE_SCRIPT',
    source_system: 'BLOCKCHAIN_TEST_SCRIPT',
    created_by: 'nix',

    created_at: tx.createdAt,
    updated_at: tx.createdAt,
    completed_at: tx.createdAt
  };

  const insertColumns = [];
  const insertValues = [];
  const placeholders = [];

  Object.entries(valuesByColumn).forEach(([column, value]) => {
    if (hasColumn(transactionColumns, column)) {
      insertColumns.push(column);
      insertValues.push(value);
      placeholders.push(`$${insertValues.length}`);
    }
  });

  if (insertColumns.length === 0) {
    throw new Error('No matching columns found in blockchain.transactions');
  }

  const result = await client.query(
    `
    INSERT INTO blockchain.transactions (${insertColumns.join(', ')})
    VALUES (${placeholders.join(', ')})
    RETURNING *
    `,
    insertValues
  );

  return result.rows[0];
}

async function main() {
  const pool = getPool();
  const client = await pool.connect();

  const generatedRows = [];

  try {
    const walletColumns = await getColumns(client, 'wallets');
    const transactionColumns = await getColumns(client, 'transactions');

    const balanceColumn = hasColumn(walletColumns, 'current_balance')
      ? 'current_balance'
      : hasColumn(walletColumns, 'current_Balance')
        ? 'current_Balance'
        : null;

    if (!balanceColumn) {
      throw new Error('No current_balance column found in blockchain.wallets');
    }

    const walletResult = await client.query(
      `
      SELECT
        wallet_id,
        wallet_address,
        customer_id,
        organization_id,
        COALESCE(wallet_type, 'CUSTOMER') AS wallet_type,
        COALESCE(${balanceColumn}, 0) AS current_balance,
        COALESCE(currency_code, currency, $1) AS currency_code,
        COALESCE(status, 'ACTIVE') AS status
      FROM blockchain.wallets
      WHERE COALESCE(status, 'ACTIVE') = 'ACTIVE'
        AND wallet_address IS NOT NULL
      ORDER BY wallet_id
      `,
      [DEFAULT_CURRENCY]
    );

    const wallets = walletResult.rows;

    if (wallets.length < 2) {
      throw new Error('At least 2 ACTIVE wallets are required to generate transactions.');
    }

    console.log(`Found ${wallets.length} active wallets.`);
    console.log(`Generating ${TX_COUNT} transactions...`);

    await client.query('BEGIN');

    for (let i = 1; i <= TX_COUNT; i++) {
      let sender = randomItem(wallets);
      let receiver = randomItem(wallets);

      let safetyCounter = 0;
      while (
        sender.wallet_address === receiver.wallet_address &&
        safetyCounter < 20
      ) {
        receiver = randomItem(wallets);
        safetyCounter++;
      }

      if (sender.wallet_address === receiver.wallet_address) {
        continue;
      }

      const amount = randomAmount();
      const transactionFee = calculateTransactionFee(amount);
      const totalDebitAmount = Number((amount + transactionFee).toFixed(8));
      const currencyCode = sender.currency_code || receiver.currency_code || DEFAULT_CURRENCY;

      const transactionId = crypto.randomUUID();
      const transactionReference = generateTransactionReference();
      const ledgerTransactionId = `LEDGER_${transactionReference}`;
      const transactionHash = crypto
        .createHash('sha256')
        .update(`${transactionReference}_${sender.wallet_address}_${receiver.wallet_address}_${amount}`)
        .digest('hex');

      const createdAt = new Date();

      const tx = {
        transactionId,
        transactionReference,
        ledgerTransactionId,
        transactionHash,

        senderWalletId: sender.wallet_id,
        receiverWalletId: receiver.wallet_id,

        senderWalletAddress: sender.wallet_address,
        receiverWalletAddress: receiver.wallet_address,

        senderCustomerId: sender.customer_id,
        receiverCustomerId: receiver.customer_id,

        senderOrganizationId: sender.organization_id,
        receiverOrganizationId: receiver.organization_id,

        amount,
        transactionFee,
        totalDebitAmount,
        currencyCode,
        createdAt
      };

      const insertedTransaction = await insertDynamicTransaction(
        client,
        transactionColumns,
        tx
      );

      await client.query(
        `
        UPDATE blockchain.wallets
        SET ${balanceColumn} = COALESCE(${balanceColumn}, 0) - $1,
            updated_at = NOW()
        WHERE wallet_address = $2
        `,
        [totalDebitAmount, sender.wallet_address]
      );

      await client.query(
        `
        UPDATE blockchain.wallets
        SET ${balanceColumn} = COALESCE(${balanceColumn}, 0) + $1,
            updated_at = NOW()
        WHERE wallet_address = $2
        `,
        [amount, receiver.wallet_address]
      );

      generatedRows.push({
        rowNumber: i,
        transactionId:
          insertedTransaction.transaction_id ||
          insertedTransaction.id ||
          transactionId,
        transactionReference,
        senderWalletAddress: sender.wallet_address,
        receiverWalletAddress: receiver.wallet_address,
        senderCustomerId: sender.customer_id,
        receiverCustomerId: receiver.customer_id,
        amount,
        transactionFee,
        totalDebitAmount,
        currencyCode,
        status: 'CONFIRMED',
        createdAt: createdAt.toISOString()
      });

      if (i % 50 === 0) {
        console.log(`Generated ${i}/${TX_COUNT} transactions...`);
      }
    }

    await client.query('COMMIT');

    const outputDir = path.join(process.cwd(), 'outputs');
    fs.mkdirSync(outputDir, { recursive: true });

    const timestamp = new Date().toISOString().replace(/[:.]/g, '-');
    const csvFile = path.join(outputDir, `generated_wallet_transactions_${timestamp}.csv`);

    const csvHeader = [
      'row_number',
      'transaction_id',
      'transaction_reference',
      'sender_wallet_address',
      'receiver_wallet_address',
      'sender_customer_id',
      'receiver_customer_id',
      'amount',
      'transaction_fee',
      'total_debit_amount',
      'currency_code',
      'status',
      'created_at'
    ];

    const csvLines = [
      csvHeader.join(','),
      ...generatedRows.map((row) =>
        [
          row.rowNumber,
          row.transactionId,
          row.transactionReference,
          row.senderWalletAddress,
          row.receiverWalletAddress,
          row.senderCustomerId,
          row.receiverCustomerId,
          row.amount,
          row.transactionFee,
          row.totalDebitAmount,
          row.currencyCode,
          row.status,
          row.createdAt
        ].map(csvEscape).join(',')
      )
    ];

    fs.writeFileSync(csvFile, csvLines.join('\n'), 'utf8');

    console.log('====================================================');
    console.log('Wallet transaction generation completed.');
    console.log(`Generated transactions: ${generatedRows.length}`);
    console.log(`CSV file: ${csvFile}`);
    console.log('====================================================');
  } catch (error) {
    await client.query('ROLLBACK');

    console.error('Transaction generation failed:', {
      message: error.message,
      code: error.code,
      detail: error.detail,
      table: error.table,
      column: error.column,
      constraint: error.constraint
    });

    process.exitCode = 1;
  } finally {
    client.release();

    if (pool.end) {
      await pool.end();
    }
  }
}

main();
